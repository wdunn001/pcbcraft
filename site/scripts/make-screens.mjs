// Builds the product images in src/assets/screens/ from full-window sources.
// Context: src/data/screens.json is the catalog (crop, origin, alt). Sources are full 1920 by 1240
// PNGs: real captures (`pcbcraft --sample --tab pcb --size 1920x1240 --capture FILE`, 1x) and
// design renders of the app mockup (2x, named NAME@2x.png). Each entry becomes WebP and PNG, plus
// a -m pair when it has a mobile crop. Writes src/assets/screens/MANIFEST.md.
// Run: node scripts/make-screens.mjs --captures DIR --renders DIR   (needs sharp)
// Do not: edit the files by hand; change the catalog and rerun. Missing alt text fails the run.
import sharp from 'sharp';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const arg = (n) => process.argv[process.argv.indexOf(n) + 1];
const dirs = { capture: arg('--captures'), 'design-render': arg('--renders') };
if (!dirs.capture || !dirs['design-render']) throw new Error('usage: --captures DIR --renders DIR');
const catalog = JSON.parse(readFileSync(join(root, 'src/data/screens.json'), 'utf8'));
const out = join(root, 'src/assets/screens');
mkdirSync(out, { recursive: true });
const rows = [];

async function cut(file, scale, crop, name) {
  const [x, y, w, h] = crop.map((v) => v * scale);
  const img = sharp(file).extract({ left: x, top: y, width: w, height: h });
  await img.clone().webp({ quality: 88, effort: 6 }).toFile(join(out, `${name}.webp`));
  await img.clone().png({ compressionLevel: 9, palette: true, quality: 95 }).toFile(join(out, `${name}.png`));
  return [w, h];
}

for (const [id, e] of Object.entries(catalog.images)) {
  if (!e.alt || e.alt.length < 20) throw new Error(`${id}: alt text is required`);
  const scale = e.origin === 'capture' ? 1 : 2;
  const file = join(dirs[e.origin], e.origin === 'capture' ? `${e.source}.png` : `${e.source}@2x.png`);
  const [w, h] = await cut(file, scale, e.crop, id);
  if (e.mobile) await cut(file, scale, e.mobile, `${id}-m`);
  rows.push(`| ${id} | ${e.origin === 'capture' ? 'real capture' : 'design render'} | ${e.source} | ${w} x ${h} |`);
}
writeFileSync(join(out, 'MANIFEST.md'),
  `# Product images\n\nGenerated by scripts/make-screens.mjs from src/data/screens.json. Do not edit by hand.\n` +
  `Real captures come from the PCBCraft app at 1x. Design renders come from the app design mockup at 2x, for views where the app does not match the design yet.\n\n` +
  `| Image | Origin | Source view | Size (px) |\n|---|---|---|---|\n${rows.join('\n')}\n\nSlots that reuse an image are listed under "slots" in the catalog.\n`);
console.log(rows.join('\n'));
