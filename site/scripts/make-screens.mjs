// Builds every real-screenshot image of the site from the full-window captures of the app.
// Context: `cargo xtask screenshots --out DIR` writes 1920 by 1240 PNGs of the running app, one per
// view. src/data/screens.json (product images, src/assets/screens/) and src/data/guide-shots.json
// (user guide images, src/assets/guide/) say which view and which crop each file comes from.
// Each product image becomes WebP and PNG, plus a -m pair when it has a mobile crop. The social
// card is a 1200 by 630 crop. Writes src/assets/screens/MANIFEST.md.
// Run: node scripts/make-screens.mjs --captures DIR   (needs sharp). One command per refresh.
// Do not: edit the files by hand, composite or retouch a capture; change a catalog and rerun.
// A missing capture or missing alt text fails the run.
import sharp from 'sharp';
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const arg = (n) => process.argv[process.argv.indexOf(n) + 1];
const dir = process.argv.includes('--captures') ? arg('--captures') : '';
if (!dir) throw new Error('usage: node scripts/make-screens.mjs --captures DIR   (DIR from `cargo xtask screenshots --out DIR`)');
const read = (p) => JSON.parse(readFileSync(join(root, p), 'utf8'));
const catalog = read('src/data/screens.json');
const guide = read('src/data/guide-shots.json');
const shots = join(root, 'src/assets/screens');
const guideOut = join(root, 'src/assets/guide');
const publicOut = join(root, 'public');
mkdirSync(shots, { recursive: true });
mkdirSync(guideOut, { recursive: true });
const rows = [];

function source(name) {
  const file = join(dir, `${name}.png`);
  if (!existsSync(file)) throw new Error(`missing capture ${file}; run cargo xtask screenshots --out ${dir}`);
  return file;
}
function crop(file, [left, top, width, height]) {
  return sharp(file).extract({ left, top, width, height });
}

for (const [id, e] of Object.entries(catalog.images)) {
  if (!e.alt || e.alt.length < 20) throw new Error(`${id}: alt text is required`);
  const file = source(e.source);
  const cut = async (box, name) => {
    const img = crop(file, box);
    await img.clone().webp({ quality: 88, effort: 6 }).toFile(join(shots, `${name}.webp`));
    await img.clone().png({ compressionLevel: 9, palette: true, quality: 95 }).toFile(join(shots, `${name}.png`));
  };
  await cut(e.crop, id);
  if (e.mobile) await cut(e.mobile, `${id}-m`);
  rows.push(`| ${id} | ${e.source} | ${e.crop[2]} x ${e.crop[3]} |`);
}

for (const [name, e] of Object.entries(guide.images)) {
  await crop(source(e.source), e.crop).png({ compressionLevel: 9, palette: true, quality: 95 }).toFile(join(guideOut, `${name}.png`));
  rows.push(`| guide/${name} | ${e.source} | ${e.crop[2]} x ${e.crop[3]} |`);
}

const card = guide.social;
await crop(source(card.source), card.crop).png({ compressionLevel: 9 }).toFile(join(publicOut, 'social-card.png'));
rows.push(`| social-card | ${card.source} | ${card.crop[2]} x ${card.crop[3]} |`);

writeFileSync(join(shots, 'MANIFEST.md'),
  `# Product images\n\nGenerated by scripts/make-screens.mjs from src/data/screens.json and src/data/guide-shots.json. Do not edit by hand.\n` +
  `Every image is a crop of a real capture of the PCBCraft app (cargo xtask screenshots), never a mockup.\n\n` +
  `| Image | Capture | Size (px) |\n|---|---|---|\n${rows.join('\n')}\n\nSlots that reuse an image are listed under "slots" in the catalog.\n`);
console.log(rows.join('\n'));
