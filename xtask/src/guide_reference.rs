//! Generates the reference section of the user guide from the text catalog
//! and the engine command table, so it cannot drift from the app.
//!
//! # Rules
//! - Pure: `generate` maps catalog entries and command rows to page texts keyed by repo path.
//! - Labels are written as `{{ui:key}}` directives so `guide-check` keeps them honest.
//! - Every `shortcut.*` and `check.*` key appears exactly once.
//!
//! # Dependencies
//! - crates/text/strings/en.txt
//! - crates/engine/src/lib.rs
//! - xtask/src/guide_check.rs
//!
//! # Do not
//! - Hand-edit docs/guide/en/reference/; run `cargo xtask guide-check --write-reference`.
use std::collections::BTreeMap;

/// Where generated pages live, relative to the repo root.
pub const REFERENCE_DIR: &str = "docs/guide/en/reference";

/// One engine command as the reference shows it.
pub struct CommandRow {
    /// Command id such as `project.rename`.
    pub id: String,
    /// One-sentence description from the command table.
    pub description: String,
    /// Parameter names with whether each is required.
    pub params: Vec<(String, bool)>,
}

/// Reads the command table. Replace with the `site-data` JSON loader when that lands (#713).
pub fn load_commands() -> Vec<CommandRow> {
    pcbcraft_engine::commands()
        .into_iter()
        .map(|c| {
            let required: Vec<&str> = c
                .input_schema
                .get("required")
                .and_then(|r| r.as_array())
                .map(|a| a.iter().filter_map(|v| v.as_str()).collect())
                .unwrap_or_default();
            let params = c
                .input_schema
                .get("properties")
                .and_then(|p| p.as_object())
                .map(|o| {
                    o.keys()
                        .map(|k| (k.clone(), required.contains(&k.as_str())))
                        .collect()
                })
                .unwrap_or_default();
            CommandRow {
                id: c.id.to_string(),
                description: c.description.to_string(),
                params,
            }
        })
        .collect()
}

/// Front matter and generated notice shared by every reference page.
fn header(title: &str) -> String {
    format!(
        "---\ntitle: {title}\narea: ui-shell\nkind: reference\nstory: \nshots: []\nsince: 0.1\n---\n\
         <!-- Generated by cargo xtask guide-check --write-reference. Do not edit. -->\n\n"
    )
}

/// Keeps a table cell on one line.
fn cell(text: &str) -> String {
    text.replace('|', "/").replace('\n', " ")
}

/// Label keys under a prefix, in catalog order, each with its description.
/// A description is the `.tip` entry, or the sentence entry that follows the label.
fn labelled(entries: &[(String, String)], prefix: &str) -> Vec<(String, String)> {
    let tips: BTreeMap<&str, &str> = entries
        .iter()
        .map(|(k, v)| (k.as_str(), v.as_str()))
        .collect();
    let mut out: Vec<(String, String)> = Vec::new();
    let mut last_label: Option<usize> = None;
    for (key, value) in entries.iter().filter(|(k, _)| k.starts_with(prefix)) {
        if key.ends_with(".tip") {
            continue;
        }
        if value.trim_end().ends_with('.') {
            if let Some(i) = last_label.take()
                && let Some(row) = out.get_mut(i)
                && row.1.is_empty()
            {
                row.1 = value.clone();
            }
            continue;
        }
        let tip = tips
            .get(format!("{key}.tip").as_str())
            .copied()
            .unwrap_or("");
        out.push((key.clone(), tip.to_string()));
        last_label = Some(out.len() - 1);
    }
    out
}

/// A two-column table of labels and descriptions.
fn label_table(rows: &[(String, String)]) -> String {
    let mut out = String::from("| Label | What it does |\n| --- | --- |\n");
    for (key, desc) in rows {
        out.push_str(&format!("| {{{{ui:{key}}}}} | {} |\n", cell(desc)));
    }
    out
}

/// Menus page: every `menu.*` label with its tip.
fn menus(entries: &[(String, String)]) -> String {
    let rows = labelled(entries, "menu.");
    format!(
        "{}Every menu and menu entry, in the order the app shows them.\n\n{}",
        header("Menus"),
        label_table(&rows)
    )
}

/// Tools page: the tool strip and the workbench tabs.
fn tools(entries: &[(String, String)]) -> String {
    let tools = labelled(entries, "board.tool_strip.");
    let tabs = labelled(entries, "docks.workbench_tabs.");
    format!(
        "{}The tools on the tool strip.\n\n{}\n## Tabs\n\nThe tabs along the top of the workbench.\n\n{}",
        header("Tools and tabs"),
        label_table(&tools),
        label_table(&tabs)
    )
}

/// Shortcuts page: every `shortcut.*` key once, grouped by what the key holds.
fn shortcuts(entries: &[(String, String)]) -> String {
    let group = |pred: &dyn Fn(&str) -> bool| -> String {
        let mut s = String::from("| Text | Catalog key |\n| --- | --- |\n");
        for (k, v) in entries
            .iter()
            .filter(|(k, _)| k.starts_with("shortcut.") && pred(k))
        {
            s.push_str(&format!("| {} | `{k}` |\n", cell(v)));
        }
        s
    };
    format!(
        "{}Every keyboard shortcut entry the app lists.\n\n## Actions\n\n{}\n## Keys\n\n{}\n## Where they work\n\n{}",
        header("Keyboard shortcuts"),
        group(&|k| !k.starts_with("shortcut.keys.") && !k.starts_with("shortcut.context.")),
        group(&|k| k.starts_with("shortcut.keys.")),
        group(&|k| k.starts_with("shortcut.context."))
    )
}

/// Checks page: every `check.*` key once with its label.
fn checks(entries: &[(String, String)]) -> String {
    let mut s = String::from("| Check | Catalog key |\n| --- | --- |\n");
    for (k, v) in entries.iter().filter(|(k, _)| is_check_key(k)) {
        s.push_str(&format!("| {} | `{k}` |\n", cell(v)));
    }
    format!(
        "{}The design checks, as the Checks tab names them.\n\n{s}",
        header("Checks")
    )
}

/// Whether a catalog key is a check name (`check.<name>`, not `checks.*`).
fn is_check_key(key: &str) -> bool {
    key.starts_with("check.")
}

/// Settings page: every settings label with its tip.
fn settings(entries: &[(String, String)]) -> String {
    let rows: Vec<(String, String)> = labelled(entries, "settings.")
        .into_iter()
        .filter(|(k, _)| {
            !k.ends_with(".settings")
                && entries
                    .iter()
                    .any(|(e, v)| e == k && v.chars().any(|c| c.is_lowercase()))
        })
        .collect();
    format!(
        "{}Every setting, in the order the Settings tab shows them.\n\n{}",
        header("Settings"),
        label_table(&rows)
    )
}

/// Commands page: the engine command table, also served to the command line and MCP.
fn commands_page(commands: &[CommandRow]) -> String {
    let mut s = String::from("| Command | What it does | Parameters |\n| --- | --- | --- |\n");
    for c in commands {
        let params: Vec<String> = c
            .params
            .iter()
            .map(|(n, req)| {
                if *req {
                    format!("`{n}`")
                } else {
                    format!("`{n}` (optional)")
                }
            })
            .collect();
        s.push_str(&format!(
            "| `{}` | {} | {} |\n",
            c.id,
            cell(&c.description),
            params.join(", ")
        ));
    }
    format!(
        "{}The commands the engine accepts. The command line and the assistant server use the same list.\n\n{s}",
        header("Commands")
    )
}

/// All generated pages, keyed by repo-relative path.
pub fn generate(entries: &[(String, String)], commands: &[CommandRow]) -> BTreeMap<String, String> {
    let mut out = BTreeMap::new();
    let mut put = |name: &str, text: String| {
        out.insert(format!("{REFERENCE_DIR}/{name}.md"), text);
    };
    put("menus", menus(entries));
    put("tools", tools(entries));
    put("shortcuts", shortcuts(entries));
    put("checks", checks(entries));
    put("settings", settings(entries));
    put("commands", commands_page(commands));
    out
}

/// Compares fresh pages with the files on disk. `read` returns a path's current text.
pub fn check_fresh(
    fresh: &BTreeMap<String, String>,
    read: &dyn Fn(&str) -> Option<String>,
) -> Vec<String> {
    fresh
        .iter()
        .filter(|(path, text)| read(path).as_deref() != Some(text.as_str()))
        .map(|(path, _)| format!("{path} is stale; run cargo xtask guide-check --write-reference"))
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    fn entries() -> Vec<(String, String)> {
        [
            ("menu.file", "File"),
            ("menu.file.tip", "Start, open, save."),
            ("shortcut.undo_the_last_action", "Undo the last action"),
            ("shortcut.keys.scroll", "Scroll"),
            ("shortcut.context.pcb_tab", "pcb tab"),
            ("check.clearance", "Clearance"),
            ("check.unrouted", "Unrouted"),
            ("checks.measure.part_count_above", "More parts than"),
            ("board.tool_strip.route", "Route"),
            (
                "board.tool_strip.route_tool_click_two_pads",
                "Route tool: click two pads.",
            ),
        ]
        .iter()
        .map(|(k, v)| (k.to_string(), v.to_string()))
        .collect()
    }

    fn count(page: &str, key: &str) -> usize {
        page.matches(&format!("`{key}`")).count()
    }

    #[test]
    fn reference_pages_list_every_shortcut_key() {
        let pages = generate(&entries(), &[]);
        let page = pages
            .get(&format!("{REFERENCE_DIR}/shortcuts.md"))
            .cloned()
            .unwrap_or_default();
        for key in [
            "shortcut.undo_the_last_action",
            "shortcut.keys.scroll",
            "shortcut.context.pcb_tab",
        ] {
            assert_eq!(count(&page, key), 1, "{key}");
        }
    }

    #[test]
    fn reference_pages_list_every_check_key() {
        let pages = generate(&entries(), &[]);
        let page = pages
            .get(&format!("{REFERENCE_DIR}/checks.md"))
            .cloned()
            .unwrap_or_default();
        assert_eq!(count(&page, "check.clearance"), 1);
        assert_eq!(count(&page, "check.unrouted"), 1);
        assert_eq!(count(&page, "checks.measure.part_count_above"), 0);
    }

    #[test]
    fn a_stale_reference_page_fails_guide_check() {
        let mut fresh = generate(&entries(), &[]);
        let disk = fresh.clone();
        let read = |p: &str| disk.get(p).cloned();
        assert!(check_fresh(&fresh, &read).is_empty());
        let rows = [CommandRow {
            id: "new.command".into(),
            description: "A new one".into(),
            params: vec![],
        }];
        fresh = generate(&entries(), &rows);
        let stale = check_fresh(&fresh, &read);
        assert_eq!(stale.len(), 1);
        assert!(stale.iter().any(|e| e.contains("commands.md")));
        assert!(fresh.values().any(|t| t.contains("new.command")));
    }
}
