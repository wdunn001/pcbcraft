//! The showcase design as data: parts, pin-to-net assignments and positions.
//!
//! An original battery-powered environment sensor node, 55 parts on three
//! schematic pages. Where each part sits on its page lives in `schematic.rs`.
//!
//! # Rules
//! - Net names are the only connectivity; every pin of a part is listed once.
//! - Board coordinates are millimetres from the top-left corner of the board.
//!
//! # Dependencies
//! - xtask/src/showcase/parts.rs
//!
//! # Do not
//! - Name a real manufacturer part; values stay generic.

/// One placed part.
pub struct Part {
    pub reference: &'static str,
    pub symbol: &'static str,
    pub value: &'static str,
    pub footprint: &'static str,
    /// Body height in millimetres for the 3D view.
    pub height: f64,
    /// Short description kept as a component property for the bill of materials.
    pub note: &'static str,
}

const fn part(
    reference: &'static str,
    symbol: &'static str,
    value: &'static str,
    footprint: &'static str,
    height: f64,
    note: &'static str,
) -> Part {
    Part {
        reference,
        symbol,
        value,
        footprint,
        height,
        note,
    }
}

