def esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def write_term(f, t: dict[str, Any]) -> None:
    f.write("[[term]]\n")
    f.write(f'id = "{esc(t["id"])}"\n')
    f.write(f'term = "{esc(t["term"])}"\n')
    f.write(f'category = "{esc(t["category"])}"\n')
    f.write(f'short = "{esc(t["short"])}"\n')
    f.write(f'long = "{esc(t["long"])}"\n')
    syns = t.get("synonyms") or []
    f.write("synonyms = [")
    f.write(", ".join(f'"{esc(s)}"' for s in syns))
    f.write("]\n")
    rel = t.get("related") or []
    f.write("related = [")
    f.write(", ".join(f'"{esc(r)}"' for r in rel))
    f.write("]\n")
    units = t.get("units") or ""
    f.write(f'units = "{esc(units)}"\n')
    ipc = t.get("in_pcbcraft") or []
    f.write("in_pcbcraft = [")
    f.write(", ".join(f'"{esc(c)}"' for c in ipc))
    f.write("]\n")
    f.write(f'search = "{esc(t["search"])}"\n')
    calc = t.get("calculator")
    if calc:
        f.write(f'calculator = "{esc(calc)}"\n')
    f.write(f'source = "{esc(t["source"])}"\n')
    f.write("\n")


def main() -> None:
    root = pathlib.Path(__file__).resolve().parent / "parts"
    root.mkdir(parents=True, exist_ok=True)
    total = 0
    for name, terms in sorted(PARTS.items()):
        path = root / f"{name}.toml"
        with path.open("w", encoding="utf-8", newline="\n") as f:
            f.write(f'# Glossary part {name}\nschema = 1\n\n')
            for t in terms:
                write_term(f, t)
                total += 1
    print(f"wrote {total} terms in {len(PARTS)} parts under {root}")


if __name__ == "__main__":
    main()
