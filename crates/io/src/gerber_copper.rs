//! Multi-layer copper Gerber export with simplified pour regions.

use crate::bitmap_trace::simplify_ring;
use pcbcraft_doc::{CopperZone, Footprint, Layer, Project};
use pcbcraft_geom::Point;
use std::collections::BTreeMap;

pub(crate) const MAX_LAYER_OPS: usize = 1_000_000;
const MAX_APERTURES: usize = 64;
const POUR_SIMPLIFY_MM: f64 = 0.001;
const POUR_SIMPLIFY_MAX_VERTICES: usize = 500_000;

#[derive(Clone, PartialEq, Eq, PartialOrd, Ord)]
enum Ap {
    Circle(u64),
    Rect(u64, u64),
    Obround(u64, u64),
    Round(u64, u64, u64),
    Track(u64),
}

struct LayerFile {
    apertures: BTreeMap<Ap, u32>,
    body: String,
    ops: usize,
    scale: f64,
    max_ops: usize,
    notes: Vec<String>,
}

impl LayerFile {
    fn new(scale: f64, max_ops: usize) -> Self {
        Self {
            apertures: BTreeMap::new(),
            body: String::new(),
            ops: 0,
            scale,
            max_ops,
            notes: Vec::new(),
        }
    }

    fn code(&mut self, ap: Ap) -> Result<u32, String> {
        if let Some(code) = self.apertures.get(&ap) {
            return Ok(*code);
        }
        if self.apertures.len() >= MAX_APERTURES {
            return Err("gerber export needs more than 64 distinct apertures".into());
        }
        let code = 10 + self.apertures.len() as u32;
        self.apertures.insert(ap, code);
        Ok(code)
    }

    fn check_ops(&mut self, add: usize) -> Result<(), String> {
        self.ops += add;
        if self.ops > self.max_ops {
            return Err("gerber export exceeds the object limit".into());
        }
        Ok(())
    }

    fn flash(&mut self, code: u32, x: f64, y: f64) -> Result<(), String> {
        self.check_ops(1)?;
        self.body.push_str(&format!(
            "D{code}X{:.6}Y{:.6}D03*\n",
            x * self.scale,
            y * self.scale
        ));
        Ok(())
    }

    fn stroke(&mut self, code: u32, points: &[(f64, f64)], closed: bool) -> Result<(), String> {
        self.check_ops(points.len())?;
        self.body.push_str(&format!("D{code}D02*\n"));
        for (i, (x, y)) in points.iter().enumerate() {
            self.body.push_str(&format!(
                "X{:.6}Y{:.6}D0{}*\n",
                x * self.scale,
                y * self.scale,
                if i == 0 { 2 } else { 1 }
            ));
        }
        if closed && let Some((x, y)) = points.first() {
            self.body.push_str(&format!(
                "X{:.6}Y{:.6}D01*\n",
                x * self.scale,
                y * self.scale
            ));
        }
        Ok(())
    }

    fn fill_closed(&mut self, code: u32, points: &[(f64, f64)]) -> Result<(), String> {
        let add = points.len() + if points.len() >= 3 { 1 } else { 0 };
        self.check_ops(add)?;
        self.body.push_str(&format!("G36*\nD{code}D02*\n"));
        for (i, (x, y)) in points.iter().enumerate() {
            self.body.push_str(&format!(
                "X{:.6}Y{:.6}D0{}*\n",
                x * self.scale,
                y * self.scale,
                if i == 0 { 2 } else { 1 }
            ));
        }
        if points.len() >= 3
            && let Some((x, y)) = points.first()
        {
            self.body.push_str(&format!(
                "X{:.6}Y{:.6}D01*\n",
                x * self.scale,
                y * self.scale
            ));
        }
        self.body.push_str("G37*\n");
        Ok(())
    }

    fn finish(&self, comment: &str, file_function: &str) -> String {
        let mo = if self.scale != 1.0 {
            "%MOIN*%"
        } else {
            "%MOMM*%"
        };
        let mut out = format!("G04 {comment} generated by PCBCraft *\n%FSLAX46Y46*%\n{mo}\n");
        out.push_str(&format!("%TF.FileFunction,{file_function}*%\n"));
        for note in &self.notes {
            out.push_str(&format!("G04 {note} *\n"));
        }
        for (ap, code) in &self.apertures {
            if matches!(ap, Ap::Track(_)) {
                out.push_str("%TA.AperFunction,Conductor,Cu*%\n");
            }
            match *ap {
                Ap::Circle(d) | Ap::Track(d) => out.push_str(&format!(
                    "%ADD{code}C,{:.6}*%\n",
                    d as f64 / 1000.0 * self.scale
                )),
                Ap::Rect(w, h) => out.push_str(&format!(
                    "%ADD{code}R,{:.6}X{:.6}*%\n",
                    w as f64 / 1000.0 * self.scale,
                    h as f64 / 1000.0 * self.scale
                )),
                Ap::Obround(w, h) => out.push_str(&format!(
                    "%ADD{code}O,{:.6}X{:.6}*%\n",
                    w as f64 / 1000.0 * self.scale,
                    h as f64 / 1000.0 * self.scale
                )),
                Ap::Round(w, h, r) => out.push_str(&format!(
                    "%ADD{code}R2,{} R1,{:.6}X{:.6} {r} 0 0*%\n",
                    if r * 2 == h {
                        "0".to_string()
                    } else {
                        format!("{:.6}", r as f64 / 1000.0 * self.scale)
                    },
                    w as f64 / 1000.0 * self.scale,
                    h as f64 / 1000.0 * self.scale
                )),
            }
        }
        out.push_str("%LPD*%\nG01*\n");
        out.push_str(&self.body);
        out.push_str("M02*\n");
        out
    }
}

fn copper_file_meta(p: &Project, idx: u8) -> (String, String, bool) {
    let last = p.copper_layer_count().saturating_sub(1);
    let l_num = idx + 1;
    if idx == 0 {
        (
            "pcb-F.Cu.gbr".into(),
            format!("Copper,L{l_num},Top"),
            false,
        )
    } else if idx == last {
        (
            "pcb-B.Cu.gbr".into(),
            format!("Copper,L{l_num},Bot"),
            true,
        )
    } else {
        (
            format!("pcb-In{idx}.Cu.gbr"),
            format!("Copper,L{l_num},Inr"),
            false,
        )
    }
}

fn ring_to_points(ring: &[Point], mirror_x: bool) -> Vec<(f64, f64)> {
    ring.iter()
        .map(|q| {
            if mirror_x {
                (-q.x, q.y)
            } else {
                (q.x, q.y)
            }
        })
        .collect()
}

fn close_ring(mut ring: Vec<(f64, f64)>) -> Vec<(f64, f64)> {
    if ring.len() >= 2 {
        let (fx, fy) = ring[0];
        if let Some(&(lx, ly)) = ring.last()
            && ((fx - lx).abs() > 1e-9 || (fy - ly).abs() > 1e-9)
        {
            ring.push((fx, fy));
        }
    }
    ring
}

fn pour_ring_ops(rings: &[Vec<(f64, f64)>]) -> usize {
    rings.iter().map(|r| r.len() + if r.len() >= 3 { 1 } else { 0 }).sum()
}

fn simplify_pour_rings(
    piece: &pcbcraft_geom::poly::Piece,
    mirror_x: bool,
    tolerance: f64,
) -> Vec<Vec<(f64, f64)>> {
    piece
        .iter()
        .map(|ring| {
            let raw = ring_to_points(ring, mirror_x);
            let open = if raw.len() >= 2
                && (raw[0].0 - raw[raw.len() - 1].0).abs() < 1e-9
                && (raw[0].1 - raw[raw.len() - 1].1).abs() < 1e-9
            {
                raw[..raw.len() - 1].to_vec()
            } else {
                raw
            };
            let simplified = simplify_ring(open, tolerance, POUR_SIMPLIFY_MAX_VERTICES);
            close_ring(simplified)
        })
        .collect()
}

fn write_pour_piece(
    file: &mut LayerFile,
    code: u32,
    piece: &pcbcraft_geom::poly::Piece,
    mirror_x: bool,
    headroom: usize,
) -> Result<bool, String> {
    let mut tolerance = POUR_SIMPLIFY_MM;
    loop {
        let rings = simplify_pour_rings(piece, mirror_x, tolerance);
        let need = pour_ring_ops(&rings);
        if file.ops + need <= file.max_ops && need <= headroom {
            for (index, points) in rings.iter().enumerate() {
                if index > 0 {
                    file.body.push_str("%LPC*%\n");
                }
                file.fill_closed(code, points)?;
                if index > 0 {
                    file.body.push_str("%LPD*%\n");
                }
            }
            return Ok(true);
        }
        if tolerance >= 1.0 {
            return Ok(false);
        }
        tolerance *= 2.0;
    }
}

fn zone_label(p: &Project, zone: &CopperZone) -> String {
    let layer = p.layer_name(zone.layer);
    format!("zone {} on {layer}", zone.id)
}

fn write_zone_pour(
    p: &Project,
    file: &mut LayerFile,
    zone: &CopperZone,
    code: u32,
    mirror_x: bool,
) -> Result<(), String> {
    let fill = pcbcraft_doc::zone_fill(p, zone)?;
    for piece in &fill.pieces {
        let headroom = file.max_ops.saturating_sub(file.ops);
        if !write_pour_piece(file, code, piece, mirror_x, headroom)? {
            let name = zone_label(p, zone);
            file.notes.push(format!(
                "skipped pour {name}: too many vertices after simplification; widen clearance or split the zone"
            ));
            break;
        }
    }
    Ok(())
}

fn pad_ap(pad: &pcbcraft_doc::Pad) -> Ap {
    match pad.geometry.as_ref() {
        Some(g) => match g.shape.as_str() {
            "circle" => {
                let w = (g.size.x * 1_000.0).round() as u64;
                Ap::Circle(w.max(1))
            }
            "rect" => {
                let w = (g.size.x * 1_000.0).round() as u64;
                let h = (g.size.y * 1_000.0).round() as u64;
                Ap::Rect(w.max(1), h.max(1))
            }
            "oval" => {
                let w = (g.size.x * 1_000.0).round() as u64;
                let h = (g.size.y * 1_000.0).round() as u64;
                Ap::Obround(w.max(1), h.max(1))
            }
            "roundrect" => {
                let w = (g.size.x * 1_000.0).round() as u64;
                let h = (g.size.y * 1_000.0).round() as u64;
                Ap::Round(
                    w.max(1),
                    h.max(1),
                    ((w.min(h) as f64 * g.roundrect_ratio.unwrap_or(0.0))
                        .round()
                        .max(1.0)) as u64,
                )
            }
            _ => Ap::Circle((pad.diameter.max(0.001) * 1_000.0).round() as u64),
        },
        None => Ap::Circle((pad.diameter.max(0.001) * 1_000.0).round() as u64),
    }
}

fn write_footprint_pad(
    p: &Project,
    f: &Footprint,
    pad: &pcbcraft_doc::Pad,
    layer: Layer,
    file: &mut LayerFile,
    mirror_x: bool,
) -> Result<(), String> {
    let Some(g) = pad.geometry.as_ref() else {
        if layer == Layer::Front {
            let world = f.pad_world_position(pad);
            let code = file.code(pad_ap(pad))?;
            file.flash(code, world.x, world.y)?;
        }
        return Ok(());
    };
    if g.pad_type == "unplated" {
        return Ok(());
    }
    if !f.pad_on_copper(pad, layer) {
        return Ok(());
    }
    let world = f.pad_world_position(pad);
    let ap = pad_ap(pad);
    let code = file.code(ap)?;
    let (x, y) = if mirror_x {
        (-world.x, world.y)
    } else {
        (world.x, world.y)
    };
    file.flash(code, x, y)?;
    let _ = p;
    Ok(())
}

/// One Gerber copper file per stack layer, with poured regions simplified before write.
pub(crate) fn export_layers(
    p: &Project,
    scale: f64,
) -> Result<(BTreeMap<String, String>, Vec<String>), String> {
    export_layers_with_cap(p, scale, MAX_LAYER_OPS)
}

pub(crate) fn export_layers_with_cap(
    p: &Project,
    scale: f64,
    max_ops: usize,
) -> Result<(BTreeMap<String, String>, Vec<String>), String> {
    let count = p.copper_layer_count();
    let mut layers: Vec<LayerFile> = (0..count)
        .map(|_| LayerFile::new(scale, max_ops))
        .collect();
    let mut layer_at = |idx: u8| -> &mut LayerFile { &mut layers[idx as usize] };

    for idx in 0..count {
        let layer = Layer::from_index(idx)?;
        let (_, _, mirror_x) = copper_file_meta(p, idx);
        let file = layer_at(idx);
        let pour_code = file.code(Ap::Circle(1))?;
        for z in &p.board.zones {
            if !z.filled || z.layer != layer {
                continue;
            }
            write_zone_pour(p, file, z, pour_code, mirror_x)?;
        }
    }

    for t in &p.board.tracks {
        let idx = t.layer.index();
        if idx >= count {
            continue;
        }
        let (_, _, mirror_x) = copper_file_meta(p, idx);
        let file = layer_at(idx);
        let w = (t.width * 1_000.0).round() as u64;
        let code = file.code(Ap::Track(w.max(1)))?;
        let mirror = |x: f64, y: f64| -> (f64, f64) {
            if mirror_x {
                (-x, y)
            } else {
                (x, y)
            }
        };
        if let Some(arc) = t.curve() {
            file.check_ops(1)?;
            let (sx, sy) = mirror(t.start.x, t.start.y);
            let (ex, ey) = mirror(t.end.x, t.end.y);
            let (cx, cy) = mirror(arc.center.x, arc.center.y);
            let clockwise = if mirror_x {
                arc.sweep > 0.0
            } else {
                arc.sweep < 0.0
            };
            file.body.push_str(&format!(
                "D{code}D02*\nX{:.6}Y{:.6}D02*\nX{:.6}Y{:.6}I{:.6}J{:.6}G0{}*\n",
                sx * scale,
                sy * scale,
                ex * scale,
                ey * scale,
                (cx - sx) * scale,
                (cy - sy) * scale,
                if clockwise { 2 } else { 3 }
            ));
        } else {
            file.stroke(
                code,
                &[
                    mirror(t.start.x, t.start.y),
                    mirror(t.end.x, t.end.y),
                ],
                false,
            )?;
        }
    }

    for f in &p.board.footprints {
        for pad in &f.pads {
            for idx in 0..count {
                let layer = Layer::from_index(idx)?;
                let (_, _, mirror_x) = copper_file_meta(p, idx);
                write_footprint_pad(p, f, pad, layer, layer_at(idx), mirror_x)?;
            }
        }
    }

    for v in &p.board.vias {
        for layer in p.via_span_layers(v) {
            let idx = layer.index();
            if idx >= count {
                continue;
            }
            let (_, _, mirror_x) = copper_file_meta(p, idx);
            let file = layer_at(idx);
            let d = (v.diameter * 1_000.0).round() as u64;
            let code = file.code(Ap::Circle(d.max(1)))?;
            let (x, y) = if mirror_x {
                (-v.position.x, v.position.y)
            } else {
                (v.position.x, v.position.y)
            };
            file.flash(code, x, y)?;
        }
    }

    let mut warnings = Vec::new();
    let mut files = BTreeMap::new();
    for idx in 0..count {
        let (name, file_function, _) = copper_file_meta(p, idx);
        let file = &layers[idx as usize];
        for note in &file.notes {
            warnings.push(note.clone());
        }
        let comment = if idx == 0 {
            "front copper layer"
        } else if idx + 1 == count {
            "back copper layer"
        } else {
            "inner copper layer"
        };
        files.insert(name, file.finish(comment, &file_function));
    }
    Ok((files, warnings))
}
